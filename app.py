import os
import re
import uuid
from difflib import SequenceMatcher

import cloudinary
import cloudinary.uploader
import cloudinary.utils
import psycopg2
from psycopg2.extras import DictCursor
from flask import (
    Flask, render_template, request, redirect, g, send_from_directory,
    url_for, flash, abort, jsonify
)

app = Flask(__name__)
app.secret_key = os.environ.get("FLASK_SECRET_KEY")

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
VIDEO_FOLDER = os.path.join(BASE_DIR, "videos")
app.config["VIDEO_FOLDER"] = VIDEO_FOLDER
app.config["MAX_CONTENT_LENGTH"] = 100 * 1024 * 1024  # 100 MB

DATABASE_URL = os.environ.get("DATABASE_URL")

# Configure Cloudinary from Render Environment Variables.
cloudinary.config(
    cloud_name=os.environ.get("CLOUDINARY_CLOUD_NAME"),
    api_key=os.environ.get("CLOUDINARY_API_KEY"),
    api_secret=os.environ.get("CLOUDINARY_API_SECRET"),
    secure=True,
)


def connect_db():
    """Open a PostgreSQL connection to Supabase."""
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Add your Supabase PostgreSQL connection "
            "string in Render > your service > Environment."
        )

    # DictCursor preserves the existing row['column_name'] access pattern.
    return psycopg2.connect(DATABASE_URL, cursor_factory=DictCursor)


def get_db():
    if "db" not in g:
        g.db = connect_db()
    return g.db


def initialize_database():
    """Create the metadata table if it does not already exist."""
    os.makedirs(VIDEO_FOLDER, exist_ok=True)
    connection = connect_db()
    try:
        with connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS public.videos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        title TEXT NOT NULL,
                        description TEXT,
                        filename TEXT NOT NULL UNIQUE
                    )
                    """
                )
    finally:
        connection.close()


# Create the table at startup; existing rows are not deleted.
initialize_database()


@app.teardown_appcontext
def close_db(error=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def search_score(query, video):
    """Score a video against a query, allowing small spelling mistakes."""
    query_words = re.findall(r"\w+", query.casefold())
    if not query_words:
        return 0.0

    title = (video["title"] or "").casefold()
    description = (video["description"] or "").casefold()
    text = f"{title} {description}"

    if query.casefold() in title:
        return 1.0
    if query.casefold() in description:
        return 0.9

    words = re.findall(r"\w+", text)
    word_score = sum(
        max((SequenceMatcher(None, query_word, word).ratio() for word in words), default=0.0)
        for query_word in query_words
    ) / len(query_words)
    phrase_score = SequenceMatcher(None, query.casefold(), text).ratio()
    return max(word_score, phrase_score)


@app.route("/")
def index():
    search_query = request.args.get("q", "").strip()
    page = request.args.get("page", "home")
    db = get_db()

    with db.cursor() as cursor:
        if search_query:
            page = "search"
            cursor.execute(
                """
                SELECT id, title, description, filename
                FROM public.videos
                ORDER BY title
                """
            )
            all_videos = cursor.fetchall()
            exact_matches = [
                video for video in all_videos
                if search_query.casefold() in (video["title"] or "").casefold()
                or search_query.casefold() in (video["description"] or "").casefold()
            ]
            fuzzy_matches = []
            if len(search_query) >= 3:
                fuzzy_matches = [
                    (search_score(search_query, video), video)
                    for video in all_videos
                    if video not in exact_matches
                ]
                fuzzy_matches = [item for item in fuzzy_matches if item[0] >= 0.58]
                fuzzy_matches.sort(key=lambda item: (-item[0], item[1]["title"].casefold()))
            videos = exact_matches + [video for _, video in fuzzy_matches]
        else:
            cursor.execute(
                """
                SELECT id, title, description, filename
                FROM public.videos
                ORDER BY title
                """
            )
            videos = cursor.fetchall()

    return render_template(
        "index.html",
        videos=videos,
        search_query=search_query,
        page=page,
    )


@app.route("/search/suggestions")
def search_suggestions():
    query = request.args.get("q", "").strip()
    if len(query) < 2:
        return jsonify([])

    pattern = f"%{query}%"
    db = get_db()
    with db.cursor() as cursor:
        cursor.execute(
            """
            SELECT DISTINCT title
            FROM public.videos
            WHERE title ILIKE %s OR description ILIKE %s
            ORDER BY title
            LIMIT 8
            """,
            (pattern, pattern),
        )
        suggestions = [row["title"] for row in cursor.fetchall()]
    return jsonify(suggestions)


@app.route("/video/<path:filename>")
def serve_video(filename):
    # Older local records still work if the file exists in videos/.
    local_path = os.path.join(VIDEO_FOLDER, filename)
    if os.path.isfile(local_path):
        return send_from_directory(VIDEO_FOLDER, filename)

    # Cloudinary public IDs can include a folder path.
    cloud_name = os.environ.get("CLOUDINARY_CLOUD_NAME")
    if not cloud_name or not os.environ.get("CLOUDINARY_API_KEY") or not os.environ.get("CLOUDINARY_API_SECRET"):
        abort(503, description="Cloudinary is not configured on the server.")

    video_url, _ = cloudinary.utils.cloudinary_url(
        filename,
        resource_type="video",
        secure=True,
        format="mp4",
    )
    return redirect(video_url, code=302)


@app.route("/upload", methods=["POST"])
def upload_video():
    title = request.form.get("title", "").strip()
    description = request.form.get("description", "").strip()
    file = request.files.get("video")

    if not title or not file or not file.filename:
        flash("Please enter a title and select a video.")
        return redirect(url_for("index"))

    if not file.filename.lower().endswith(".mp4"):
        flash("Please upload an MP4 file.")
        return redirect(url_for("index"))

    if not all(
        os.environ.get(name)
        for name in ("CLOUDINARY_CLOUD_NAME", "CLOUDINARY_API_KEY", "CLOUDINARY_API_SECRET")
    ):
        flash("Cloudinary is not configured. Please check Render Environment Variables.")
        return redirect(url_for("index"))

    connection = None
    cloudinary_public_id = None
    try:
        # Upload the video to Cloudinary first; only metadata is stored in PostgreSQL.
        public_id = f"video-indexing-system/{uuid.uuid4().hex}"
        result = cloudinary.uploader.upload(
            file.stream,
            resource_type="video",
            public_id=public_id,
            overwrite=False,
            chunk_size=6_000_000,
        )
        cloudinary_public_id = result["public_id"]

        connection = connect_db()
        with connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO public.videos (title, description, filename)
                    VALUES (%s, %s, %s)
                    """,
                    (title, description, cloudinary_public_id),
                )

        flash("Video uploaded successfully!")
    except Exception:
        app.logger.exception("Video upload failed")
        flash("Video upload failed. Check the Render logs, Supabase connection, and Cloudinary usage limits.")
    finally:
        if connection is not None:
            connection.close()

    return redirect(url_for("index"))


if __name__ == "__main__":
    app.run(debug=False, host="0.0.0.0", port=int(os.environ.get("PORT", 5001)))
